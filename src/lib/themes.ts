export const DEFAULT_THEME_ID = "tomato-dark";

export function getTheme(id: string | undefined | null): AppTheme {
  return THEMES.find((t) => t.id === id) ?? THEMES[0];
}

/** 把主题的 UI 配色写入 :root CSS 变量，整个界面随主题联动 */
export function applyThemeVars(theme: AppTheme) {
  const root = document.documentElement;
  const u = theme.ui;
  const map: Record<string, string> = {
    "--bg": u.bg,
    "--panel": u.panel,
    "--surface": u.surface,
    "--input": u.input,
    "--border": u.border,
    "--text": u.text,
    "--text-muted": u.textMuted,
    "--accent": u.accent,
    "--accent-text": u.accentText,
    "--danger": u.danger,
    "--warning": u.warning,
    "--success": u.success,
  };
  for (const [k, v] of Object.entries(map)) root.style.setProperty(k, v);
  root.dataset.theme = theme.id;
  root.dataset.appearance = theme.dark ? "dark" : "light";
  root.style.colorScheme = theme.dark ? "dark" : "light";
}
